#!/usr/bin/env python3
"""Project immutable native OTP properties into compact production ranges."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'evidence/reference-investigations/otp-20261016'
INPUTS = {
    'native-otp-semantics.json': '1756160a526d3707215e3e227c2b8a21ac621aaac6297fc2d0bf62771ec33e05',
    'numeric-cluster-properties.json': '768b497358b4101acb5264ddfa72939551d9e7a1ef9819c816a3920d4f2971ed',
}


def read(name):
    raw = (SOURCE / name).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == INPUTS[name], f'OTP input bytes changed: {name}'
    return json.loads(raw)


def ranges(values):
    assert values == sorted(set(values))
    result = []
    for scalar in values:
        assert 0 <= scalar <= 0x10ffff and not 0xd800 <= scalar <= 0xdfff
        if result and result[-1][1] + 1 == scalar:
            result[-1][1] = scalar
        else:
            result.append([scalar, scalar])
    return result


def projected():
    semantics = read('native-otp-semantics.json')
    facts = read('numeric-cluster-properties.json')
    assert semantics['reference'] == 'fe8a1d462fbd793d883fb92086a16aa2947e32c9'
    assert len(semantics['singleScalarNumbers']) == facts['numericScalars'] == 2023
    assert facts['numericGCBClasses'] == {'Other': 2023}
    for key in ['numericExtendedPictographicOverlap', 'numericIndicConsonantOverlap',
                'joiningExtendedPictographicOverlap', 'joiningIndicConsonantOverlap']:
        assert facts[key] == [], key
    assert len(facts['joiningScalars']) == 2619 and len(facts['prependScalars']) == 27
    output = ['// Generated by scripts/generate-otp-unicode.py; do not edit.',
              '// Pinned native OTP numeric transformation, not a general grapheme engine.',
              '// Unicode property data: assets/unicode/LICENSE.txt.', '#pragma once',
              '#include <array>', 'namespace OtpUnicode {',
              'struct Range {char32_t first;char32_t last;};']
    for name, values in [('numbers', semantics['singleScalarNumbers']),
                         ('joining', facts['joiningScalars']), ('prepend', facts['prependScalars'])]:
        rows = ranges(values)
        output.append(f'inline constexpr std::array<Range,{len(rows)}> {name}{{{{')
        output.extend(f'    {{0x{lo:x},0x{hi:x}}},' for lo, hi in rows)
        output.append('}};')
    output.append('}')
    return '\n'.join(output) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/Avelino/otpunicode.h'
    expected = projected()
    if args.check:
        assert target.read_text() == expected, 'OTP Unicode projection is stale'
    else:
        target.write_text(expected)
    print('OTP Unicode projection: 2023 numbers, 2619 joining scalars, 27 prepends')
