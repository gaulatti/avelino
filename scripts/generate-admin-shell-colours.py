#!/usr/bin/env python3
"""Project pinned native caller inputs into the ordinary AdminShell fixtures."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'evidence/reference-investigations/admin-shell-colour-inputs-20261020/resolved-inputs.json'
TARGET = ROOT / 'tests/consumer/native-admin-shell-colours.js'


def encoded(value):
    return 12.92 * value if value <= 0.0031308 else 1.055 * value ** (1 / 2.4) - 0.055


def generated():
    raw = SOURCE.read_bytes()
    source = json.loads(raw)
    reference = json.loads((ROOT / 'reference/source-manifest.json').read_text())['references']['desktop']['revision']
    assert source['reference'] == reference and source['accepted'] is False
    environments = {}
    for theme in ['light', 'dark']:
        environments[theme] = {}
        assert set(source['environments'][theme]) == {'root', 'sidebar', 'header', 'content'}
        for role, row in source['environments'][theme].items():
            values = row['linearSRGB']
            assert len(values) == 4 and all(math.isfinite(v) and 0 <= v <= 1 for v in values)
            assert [struct.unpack('>f', bytes.fromhex(bits))[0] for bits in row['float32Bits']] == values
            assert row['colorScheme'] == theme and row['colorSchemeContrast'] == 'standard'
            assert row['controlActiveState'] == 'inactive' and row['displayScale'] == 2
            environments[theme][role] = dict(linearSRGB=values, float32Bits=row['float32Bits'],
                                            encodedSRGB=[encoded(v) for v in values[:3]] + values[3:])
    return ('// Generated by scripts/generate-admin-shell-colours.py from unchanged native Float32 inputs.\n'
            '// Standard sRGB transfer only; this does not convert capture ICC profiles or accept pixels.\n'
            + 'var reference = ' + json.dumps(reference) + ';\n'
            + 'var sourceSha256 = ' + json.dumps(hashlib.sha256(raw).hexdigest()) + ';\n'
            + 'var environments = ' + json.dumps(environments, indent=2) + ';\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = generated()
    if args.check:
        assert TARGET.read_text() == value, 'AdminShell caller colour projection is stale'
    else:
        TARGET.write_text(value)
