#!/usr/bin/env python3
"""Project actual native divider view geometry and appearance-resolved colours."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'evidence/reference-investigations/admin-shell-materials-20261020/observations-v3.json'
TARGET = ROOT / 'tests/components/native-admin-divider.js'


def generated():
    native = json.loads(SOURCE.read_text())
    rows = []
    for row in native['records']:
        divider = next(v for v in row['state']['nativeHierarchy'] if v['class'] == 'NSSplitDividerView')
        rows.append(dict(tag=('dark' if row['dark'] else 'light') + '-' + str(row['initial']),
                         dark=row['dark'], initial=row['initial'], visible=not divider['hiddenByAncestor'],
                         frame=divider['hostFrame'], sourceDpr=row['state']['backingScaleFactor'],
                         rgba=row['state']['dividerProperties']['sRGB']))
    return ('// Projected from the unchanged native material controls; generated by scripts/generate-admin-divider-witnesses.py.\n'
            + 'var sourceSha256 = ' + json.dumps(hashlib.sha256(SOURCE.read_bytes()).hexdigest()) + ';\n'
            + 'var rows = ' + json.dumps(rows, indent=2) + ';\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generated()
    if args.check:
        assert TARGET.read_text() == result, 'Native divider witness projection is stale'
    else:
        TARGET.write_text(result)
