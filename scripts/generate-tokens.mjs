import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import * as source from '../tokens/bleecker-source.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(fs.readFileSync(`${root}reference/source-manifest.json`));
const checksum = crypto.createHash('sha256').update(fs.readFileSync(`${root}tokens/bleecker-source.ts`)).digest('hex');
assert.equal(checksum, manifest.references.bleecker.sha256, 'Canonical token source changed without a reviewed baseline update');
const colors = Object.fromEntries(['light', 'dark'].map(mode => [mode, { ...source[`${mode}Colors`], live: mode === 'dark' ? '#34d399' : '#10b981' }]));
// Native palette in Sabella has these exact adaptations. Record them explicitly;
// do not silently substitute broader web-token colors for rendered native inputs.
colors.dark.deepSea = '#182533';
const value = { spacing: source.spacing, radii: source.radii, durations: source.durations, fontFamilies: source.fontFamilies, colors };
// Preserve the platform-neutral JSON, but construct real Qt colors for alpha
// values. QColor's string parser does not accept CSS rgba() syntax.
function qmlLiteral(data) {
  if (typeof data === 'string' && data.startsWith('rgba(')) {
    const match = /^rgba\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)$/.exec(data);
    assert.ok(match, `Unsupported canonical alpha color: ${data}`);
    const [r, g, b, a] = match.slice(1).map(Number);
    assert.ok([r, g, b].every(v => Number.isFinite(v) && v >= 0 && v <= 255)
      && Number.isFinite(a) && a >= 0 && a <= 1, `Invalid canonical alpha color: ${data}`);
    return `Qt.rgba(${r}/255,${g}/255,${b}/255,${a})`;
  }
  if (Array.isArray(data)) return `[${data.map(qmlLiteral).join(',')}]`;
  if (data && typeof data === 'object')
    return `{${Object.entries(data).map(([key, item]) => `${JSON.stringify(key)}:${qmlLiteral(item)}`).join(',')}}`;
  return JSON.stringify(data);
}
const qml = `// Generated by scripts/generate-tokens.mjs. Do not edit.\npragma Singleton\nimport QtQml\nQtObject {\n${Object.entries(value).map(([key, data]) => `    readonly property var ${key}: ${qmlLiteral(data)}`).join('\n')}\n}\n`;
const outputs = new Map([['tokens/generated.json', `${JSON.stringify(value, null, 2)}\n`], ['src/Avelino/BleeckerTokens.qml', qml]]);
for (const [relative, content] of outputs) {
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(`${root}${relative}`, 'utf8'), content, `Generated token drift: ${relative}`);
  else { fs.mkdirSync(`${root}${relative}`.split('/').slice(0, -1).join('/'), { recursive: true }); fs.writeFileSync(`${root}${relative}`, content); }
}
